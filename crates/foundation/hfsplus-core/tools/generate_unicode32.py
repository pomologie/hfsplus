#!/usr/bin/env python3
"""Generate the HFS+ canonical decomposition data with CPython's pinned UCD."""

import argparse
from pathlib import Path
import unicodedata

UNICODE_VERSION = "3.2.0"
UNICODE_LIMIT = 0x110000
SURROGATES = range(0xD800, 0xE000)
HANGUL_SYLLABLES = range(0xAC00, 0xD7A4)
HFS_DECOMPOSITION_EXCLUSIONS = (
    range(0x2000, 0x3000),
    range(0xF900, 0xFB00),
    range(0x2F800, 0x2FB00),
)
DECOMPOSITIONS_PER_LINE = 3
CLASSES_PER_LINE = 5
DESTINATION = Path(__file__).resolve().parents[1] / "src" / "names" / "unicode32.rs"


def rust_char(value):
    return f"'\\u{{{ord(value):x}}}'"


def render_rows(rows, count):
    for start in range(0, len(rows), count):
        yield "\t" + ", ".join(rows[start:start + count]) + ","


def generate():
    database = unicodedata.ucd_3_2_0
    if database.unidata_version != UNICODE_VERSION:
        raise RuntimeError(f"expected Unicode {UNICODE_VERSION}, got {database.unidata_version}")

    decompositions = []
    combining_classes = []
    for codepoint in range(UNICODE_LIMIT):
        if codepoint in SURROGATES:
            continue
        scalar = chr(codepoint)
        key = rust_char(scalar)
        combining_class = database.combining(scalar)
        if combining_class:
            combining_classes.append(f"({key}, {combining_class})")
        if codepoint in HANGUL_SYLLABLES or any(
            codepoint in excluded for excluded in HFS_DECOMPOSITION_EXCLUSIONS
        ):
            continue
        decomposed = database.normalize("NFD", scalar)
        if decomposed == scalar:
            continue
        # This static table expands each scalar in one step. A mapping through
        # an excluded child would require explicit recursive HFS+ handling.
        if any(ord(child) in excluded
               for child in decomposed for excluded in HFS_DECOMPOSITION_EXCLUSIONS):
            raise RuntimeError(f"U+{codepoint:04X} expands through an HFS+ exclusion")
        values = ", ".join(map(rust_char, decomposed))
        decompositions.append(f"({key}, &[{values}])")

    return "\n".join([
        "// SPDX-License-Identifier: Unicode-3.0",
        "// Generated by tools/generate_unicode32.py from Unicode 3.2.0 data.",
        "// Data license and provenance are recorded in this crate's UNICODE-LICENSE and docs.",
        "",
        "#[rustfmt::skip]",
        "pub(super) static DECOMPOSITIONS: &[(char, &[char])] = &[",
        *render_rows(decompositions, DECOMPOSITIONS_PER_LINE),
        "];",
        "",
        "#[rustfmt::skip]",
        "pub(super) static COMBINING_CLASSES: &[(char, u8)] = &[",
        *render_rows(combining_classes, CLASSES_PER_LINE),
        "];",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the existing generated data")
    args = parser.parse_args()
    data = generate().encode("utf-8")
    if args.check:
        if DESTINATION.read_bytes() != data:
            raise SystemExit(f"generated data differs from {DESTINATION}")
    else:
        DESTINATION.write_bytes(data)


if __name__ == "__main__":
    main()
